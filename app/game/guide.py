def _snbt_str(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') \
        .replace("\n", "\\n") + '"'


def book_command(player: str, title: str, author: str, pages) -> str:
    """Книга с текст. Заглавието е до 32 знака (иначе играта я отхвърля)."""
    body = ",".join(_snbt_str(str(p)[:1000]) for p in (pages or [""])[:50])
    return (f"give {player} written_book[written_book_content="
            f"{{title:{_snbt_str(str(title)[:32])},"
            f"author:{_snbt_str(str(author)[:32])},pages:[{body}]}}] 1")


def give_command(player: str) -> str:
    return book_command(player, "Пътеводител", "BVG WORLD", PAGES)
